from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import pandas as pd

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

REQUIRED_RESULT_GROUPS = {
    "dataset_comparison": [
        "results/cross_dataset_comparison/dataset_comparison_matrix.csv",
        "results/final_dataset_selection/final_dataset_decision.csv",
    ],
    "final_ml": [
        "results/final/ml/final_ml_metrics.csv",
        "results/final/ml/final_per_class_metrics.csv",
        "results/final/ml/final_confusion_matrix.csv",
    ],
    "dashboard": [
        "results/final/dashboard_data/ml_metrics.csv",
        "results/final/dashboard_data/class_distribution.csv",
    ],
}


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Validate completed analysis/result artifacts.")
    p.add_argument("--results-root", type=Path, default=REPO_ROOT / "results")
    return p.parse_args()


def _check_csv(path: Path, required_columns: set[str] | None = None) -> bool:
    if not path.exists():
        print(f"ERROR missing: {path}")
        return False
    try:
        df = pd.read_csv(path)
    except Exception as exc:
        print(f"ERROR unreadable: {path} ({exc})")
        return False
    if df.empty:
        print(f"WARNING empty: {path}")
    if required_columns:
        missing = required_columns - set(df.columns)
        if missing:
            print(f"ERROR {path}: missing columns {sorted(missing)}")
            return False
    print(f"OK {path.relative_to(REPO_ROOT)} rows={len(df):,} cols={len(df.columns)}")
    return True


def validate(results_root: Path) -> bool:
    root = results_root.resolve()
    if not root.exists():
        print(f"ERROR results directory does not exist: {root}")
        return False

    checks = [
        ("cross-dataset comparison", root / "cross_dataset_comparison" / "dataset_comparison_matrix.csv", {"criterion"}),
        ("final decision", root / "final_dataset_selection" / "final_dataset_decision.csv", None),
        ("final ML metrics", root / "final" / "ml" / "final_ml_metrics.csv",
         {"model", "accuracy", "balanced_accuracy", "macro_f1", "weighted_f1"}),
        ("final per-class metrics", root / "final" / "ml" / "final_per_class_metrics.csv",
         {"class", "precision", "recall", "f1", "support"}),
        ("final confusion matrix", root / "final" / "ml" / "final_confusion_matrix.csv", None),
    ]

    ok = True
    for _, path, cols in checks:
        ok &= _check_csv(path, cols)

    # The repository already contains a curated dashboard_data bundle generated by
    # the final consolidation notebook. Treat it as a first-class source rather
    # than requiring the raw processed dataset for reporting.
    dashboard = root / "final" / "dashboard_data"
    if dashboard.exists():
        csv_count = len(list(dashboard.glob("*.csv")))
        print(f"OK final dashboard bundle: {csv_count} CSV artifacts")
    else:
        print("WARNING final/dashboard_data does not exist; it will be rebuilt from results.")

    return bool(ok)


def main() -> int:
    args = parse_args()
    return 0 if validate(args.results_root) else 2


if __name__ == "__main__":
    raise SystemExit(main())
